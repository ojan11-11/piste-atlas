// Minimal no-dependency smoke tests for HTML generation and click state.
import vm from 'node:vm';
import fs from 'node:fs';
import assert from 'node:assert/strict';
const callbacks={};
const app={innerHTML:''};
const doc={title:'',querySelector:(selector)=>selector==='#app'?app:null,querySelectorAll:()=>[],createElement:()=>({textContent:''}),addEventListener:(k,fn)=>{callbacks[k]=fn},getElementById:()=>({value:'big sky'})};
const win={location:{hash:''},scrollTo:()=>{},addEventListener:(k,fn)=>{callbacks['window-'+k]=fn;}};
const sandbox={window:win,document:doc,Intl,Set,JSON,Number,String,console,alert:(msg)=>{throw new Error(msg)}};
vm.createContext(sandbox);
vm.runInContext(fs.readFileSync('data/resorts.js','utf8'),sandbox);
assert.equal(win.RESORTS.length,8);
vm.runInContext(fs.readFileSync('atlas-photos.js','utf8'),sandbox);
vm.runInContext(fs.readFileSync('atlas-extras.js','utf8'),sandbox);
vm.runInContext(fs.readFileSync('atlas-directory-map.js','utf8'),sandbox);
assert.equal(win.PisteAtlasMap._test.validCoordinate({id:'big-sky',lat:45.3,lng:-111.4}),true);
assert.equal(win.PisteAtlasMap._test.validCoordinate({id:'invalid',lat:400,lng:-111.4}),false);
assert.equal(win.PisteAtlasMap._test.clustered([{x:0,y:0},{x:5,y:5},{x:300,y:300}],p=>p,46).length,2);
assert.equal(win.PisteAtlasPhotos._test.licensed({extmetadata:{LicenseShortName:{value:'CC BY-SA 4.0'},LicenseUrl:{value:'https://creativecommons.org/licenses/by-sa/4.0/'}}}),true);
assert.equal(win.PisteAtlasPhotos._test.licensed({extmetadata:{LicenseShortName:{value:'All Rights Reserved'}}}),false);
assert.match(win.PisteAtlasExtras.passportHTML([{resort_id:'big-sky'}]),/First mountain/);
vm.runInContext(fs.readFileSync('app.js','utf8'),sandbox);
assert.match(app.innerHTML,/Every mountain/);
assert.equal((app.innerHTML.match(/class="resort-card"/g)||[]).length,8);
callbacks.click({target:{closest:(q)=>q==='[data-map-resort]'?null:{dataset:{action:'toggle-compare',id:'big-sky'}}}});
assert.match(app.innerHTML,/1 mountain selected/);
win.location.hash='#compare';callbacks['window-hashchange']();
assert.match(app.innerHTML,/Big Sky Resort/);
assert.match(app.innerHTML,/Mountain comparison/);
win.location.hash='#resort/big-sky';callbacks['window-hashchange']();
assert.match(app.innerHTML,/Official trail maps/);
assert.match(app.innerHTML,/Check official ticket prices/);
assert.match(app.innerHTML,/Photos of Big Sky Resort/);
assert.match(app.innerHTML,/Interactive mountain terrain map/);
assert.match(app.innerHTML,/Snowfall forecast/);
win.location.hash='#map';callbacks['window-hashchange']();
assert.match(app.innerHTML,/Geographic resort map/);
assert.match(app.innerHTML,/data-pa-directory-map/);
assert.match(app.innerHTML,/Fit all results/);
assert.doesNotMatch(app.innerHTML,/<svg viewBox="0 0 1000 600"/);
assert.match(app.innerHTML,/data-map-resort="big-sky"/);
win.location.hash='#about';callbacks['window-hashchange']();
assert.match(app.innerHTML,/Every mountain deserves a place/);
win.location.hash='#rankings';callbacks['window-hashchange']();
assert.match(app.innerHTML,/Top-rated mountain experiences/);
win.location.hash='#powder';callbacks['window-hashchange']();
assert.match(app.innerHTML,/Powder Finder/);
console.log('PASS: directory, geographic map coordinates and clusters, licensed photos, passport, profiles, rankings and forecasts.');
